<script>
    document.addEventListener('DOMContentLoaded', function () {
        const carousel = document.querySelector('[data-testimony-carousel]');
        if (!carousel) return;

        const items = Array.from(carousel.querySelectorAll('[data-testimony-item]'));
        const indicators = Array.from(carousel.querySelectorAll('[data-testimony-slide-to]'));
        const prevBtn = carousel.querySelector('[data-testimony-prev]');
        const nextBtn = carousel.querySelector('[data-testimony-next]');

        if (!items.length) return;

        let current = 0;

        function showSlide(index) {
            const nextIndex = (index + items.length) % items.length;

            items.forEach((el, i) => {
                const isActive = i === nextIndex;

                if (isActive) {
                    el.classList.remove('hidden');
                } else {
                    el.classList.add('hidden');
                }
            });

            current = nextIndex;

            indicators.forEach((el, i) => {
                if (i === current) {
                    el.classList.add('bg-white/50');
                    el.classList.remove('bg-white/30');
                    el.setAttribute('aria-current', 'true');
                } else {
                    el.classList.add('bg-white/30');
                    el.classList.remove('bg-white/50');
                    el.setAttribute('aria-current', 'false');
                }
            });
        }

        function next() {
            showSlide(current + 1);
        }

        function prev() {
            showSlide(current - 1);
        }

        nextBtn && nextBtn.addEventListener('click', next);
        prevBtn && prevBtn.addEventListener('click', prev);

        indicators.forEach((el) => {
            el.addEventListener('click', () => {
                const to = parseInt(el.getAttribute('data-testimony-slide-to') ?? '0', 10) || 0;
                showSlide(to);
            });
        });

        // initial state
        showSlide(0);
    });
</script>
